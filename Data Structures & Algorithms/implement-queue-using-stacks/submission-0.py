class MyQueue:

    def __init__(self):
        self.s1 = []
        self.s2 = []

    def push(self, x: int) -> None:
        self.s1.append(x)

    def pop(self) -> int:

        res = self.s1[0]
        self.s1 = self.s1[1::]
        return res

    def peek(self) -> int:
        return self.s1[0]

    def empty(self) -> bool:
        if len(self.s1) == 0:
            return True
        else:
            return False


